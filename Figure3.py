def filter_genic_sites():
    temp_bed = os.path.join(FIG3C_DIR, "_midpoints_genic_temp.bed")
    if os.path.exists(temp_bed):
        print(f"Temporary genic BED already exists: {temp_bed}")
        return temp_bed
    print("Filtering editing sites to genic regions...")
    with open(ANNOVAR_FILE, 'r') as fin, open(temp_bed, 'w') as fout:
        header = fin.readline().strip().split('\t')
        chr_idx   = header.index('Chr')
        start_idx = header.index('Start')
        func_idx  = header.index('Func.refGene')
        for line in fin:
            cols = line.rstrip('\n').split('\t')
            if cols[func_idx].lower() != 'intergenic':
                chrom = cols[chr_idx]
                start = int(cols[start_idx]) - 1
                fout.write(f"{chrom}\t{start}\t{start+1}\t.\t0\t.\n")
    print(f"Genic sites saved to {temp_bed}")
    return temp_bed


def load_sites(bed_file):
    print(f"Loading editing sites from {bed_file}...")
    df = pd.read_csv(bed_file, sep='\t', header=None, usecols=[0, 1],
                     names=['chrom', 'start'])
    df = df[df['chrom'].isin(CHROM_ORDER)]
    print(f"  Sites on canonical chromosomes: {len(df)}")
    return df


def count_per_bin(df):
    bins_list = []
    for chrom in CHROM_ORDER:
        if chrom not in CHROM_LENGTHS:
            continue
        max_pos = CHROM_LENGTHS[chrom]
        n_bins = int(np.ceil(max_pos / BIN_SIZE))
        for i in range(n_bins):
            bins_list.append({'chrom': chrom,
                              'start': i * BIN_SIZE,
                              'end':   min((i + 1) * BIN_SIZE, max_pos),
                              'bin_idx': i})
    bin_df = pd.DataFrame(bins_list)
    df = df.copy()
    df['bin_idx'] = df['start'] // BIN_SIZE
    counts = df.groupby(['chrom', 'bin_idx']).size().reset_index(name='count')
    result = bin_df.merge(counts, on=['chrom', 'bin_idx'], how='left')
    result['count'] = result['count'].fillna(0).astype(int)
    return result


def build_heatmap_matrix(counts_df):
    max_bins = counts_df.groupby('chrom').size().max()
    data = np.full((len(CHROM_ORDER), max_bins), np.nan)
    for i, chrom in enumerate(CHROM_ORDER):
        chrom_data = counts_df[counts_df['chrom'] == chrom].sort_values('start')
        if not chrom_data.empty:
            data[i, :len(chrom_data)] = chrom_data['count'].values
    return data, max_bins


def plot_heatmap(data, out_file):
    n_chrom, max_bins = data.shape
    data_plot = np.where(data == 0, np.nan, data)
    valid = data_plot[~np.isnan(data_plot)]

    fig, ax = plt.subplots(figsize=(15, n_chrom * 0.5))
    if len(valid) == 0:
        cmap = plt.cm.gray
        cmap.set_bad('lightgray')
    else:
        vmin, vmax = 1, np.percentile(valid, 99)
        if vmax <= vmin:
            vmax = vmin + 1
        cmap = plt.cm.RdYlGn_r
        cmap.set_bad("#FFFDFD")
        im = ax.imshow(data_plot, aspect='auto', cmap=cmap,
                       norm=plt.Normalize(vmin=vmin, vmax=vmax), interpolation='none')
        plt.colorbar(im, ax=ax, shrink=0.8).set_label('Number of editing sites')
    ax.set_yticks(range(n_chrom))
    ax.set_yticklabels(CHROM_ORDER)
    xticks = np.arange(0, max_bins, 10)
    ax.set_xticks(xticks)
    ax.set_xticklabels([f'{int(x * BIN_SIZE / 1e6)}' for x in xticks])
    ax.set_xlabel('Position (Mb)')
    ax.set_title('RNA Editing Site Density per Chromosome (1 Mb bins)')
    plt.tight_layout()
    plt.savefig(out_file, dpi=300)
    plt.close(fig)
    print(f"Heatmap saved to {out_file}")


def get_hot_bins(counts_df, threshold):
    hot = counts_df[counts_df['count'] > threshold].copy()
    if hot.empty:
        print(f"No bins with count > {threshold} found.")
        return None
    hot = hot.sort_values('count', ascending=False).reset_index(drop=True)
    with open(HOT_REGION_BED, 'w') as f:
        for idx, row in hot.iterrows():
            f.write(f"{row['chrom']}\t{row['start']}\t{row['end']}\t"
                    f"hot_{idx+1}\t{row['count']}\t.\n")
    print(f"{len(hot)} hot regions (> {threshold} sites/Mb) saved to {HOT_REGION_BED}")
    return hot


def prepare_protein_coding_genes_bed(gtf):
    genes_bed = os.path.join(FIG3C_DIR, "_protein_coding_genes.bed")
    if not os.path.exists(genes_bed):
        print("Extracting protein-coding genes from GTF...")
        cmd = f"""
        awk -F'\\t' '$3=="gene" {{
            split($9, a, ";"); gene_type=""; gene_name="";
            for(i in a) {{
                if(a[i] ~ /gene_type/) {{ split(a[i], b, " "); gsub(/"/, "", b[2]); gene_type=b[2]; }}
                if(a[i] ~ /gene_name/) {{ split(a[i], b, " "); gsub(/"/, "", b[2]); gene_name=b[2]; }}
            }}
            if(gene_name == "" || gene_type != "protein_coding") next;
            if(seen[gene_name]++) next;
            print $1 "\\t" $4-1 "\\t" $5 "\\t" gene_name "\\t0\\t.";
        }}' {gtf} > {genes_bed}
        """
        subprocess.run(cmd, shell=True, check=True)
    return genes_bed


def compute_gene_counts_and_overlap(editing_bed, genes_bed, hot_bed):
    print("Counting editing sites per protein-coding gene...")
    counts_file = os.path.join(FIG3C_DIR, "gene_raw_counts.tmp")
    subprocess.run(f"bedtools intersect -a {genes_bed} -b {editing_bed} -c > {counts_file}",
                   shell=True, check=True)

    genes = []
    with open(counts_file) as f:
        for line in f:
            cols = line.strip().split('\t')
            if len(cols) < 7:
                continue
            chrom, start, end, name = cols[0], int(cols[1]), int(cols[2]), cols[3]
            length = end - start
            if length == 0:
                continue
            count = int(cols[6])
            genes.append((name, chrom, start, end, count, length,
                          (count / length) * 1000))
    df = pd.DataFrame(genes, columns=['gene', 'chrom', 'start', 'end',
                                      'count', 'length', 'density'])

    overlap_genes = set()
    if os.path.exists(hot_bed) and os.path.getsize(hot_bed) > 0:
        with tempfile.NamedTemporaryFile(suffix='.tmp', delete=False) as tmp:
            tmp_name = tmp.name
        subprocess.run(
            f"bedtools intersect -a {genes_bed} -b {hot_bed} -wa -u > {tmp_name}",
            shell=True, check=True)
        with open(tmp_name) as f:
            for line in f:
                overlap_genes.add(line.strip().split('\t')[3])
        os.unlink(tmp_name)
    df['in_hot_region'] = df['gene'].isin(overlap_genes)
    return df


def plot_gene_count_top(df_genes, out_plot, title_suffix, filter_density=None):
    subset = (df_genes[df_genes['density'] > filter_density].copy()
              if filter_density is not None else df_genes.copy())
    if subset.empty:
        print(f"No genes for filter density > {filter_density}. Skipping.")
        return
    subset_sorted = subset.sort_values('count', ascending=False)
    top = subset_sorted.head(TOP_N_GENES_PLOT)
    genes_rev  = list(reversed(top['gene'].tolist()))
    counts_rev = list(reversed(top['count'].tolist()))
    colors = ['lightcoral' if flag else 'lightblue'
              for flag in reversed(top['in_hot_region'].tolist())]

    plt.figure(figsize=(12, 8))
    plt.barh(range(len(genes_rev)), counts_rev, color=colors, edgecolor='black')
    plt.yticks(range(len(genes_rev)), genes_rev, fontsize=9)
    plt.xlabel('Editing site count')
    plt.title(f'Top {TOP_N_GENES_PLOT} Protein-Coding Genes {title_suffix}')
    plt.xlim(left=20000)
    plt.legend(handles=[
        mpatches.Patch(color='lightcoral', label='Overlaps hot region'),
        mpatches.Patch(color='lightblue', label='No overlap'),
    ], loc='lower right')
    plt.tight_layout()
    plt.savefig(out_plot, dpi=300)
    plt.close()
    print(f"Gene bar plot saved to {out_plot}")


