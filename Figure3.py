def generate_midpoints():
    if os.path.exists(REF_EDITING_SITES):
        print(f"{REF_EDITING_SITES} already exists, skipping midpoint generation.")
        return
    print("Generating RefEditingsites.bed (midpoints)...")
    os.makedirs(os.path.dirname(REF_EDITING_SITES), exist_ok=True)

    def compute_midpoints(file_path):
        sites = []
        with open(file_path, 'r') as f:
            for line in f:
                if line.strip() == '':
                    continue
                parts = line.strip().split('\t')
                chrom, start, end = parts[0], int(parts[1]), int(parts[2])
                name, score, strand = parts[3], parts[4], parts[5]
                mid = start + (end - start) // 2
                sites.append([chrom, mid, mid + 1, name, score, strand])
        return sites

    all_sites = compute_midpoints(PLUS_BED) + compute_midpoints(MINUS_BED)
    with open(REF_EDITING_SITES, 'w') as out:
        for s in all_sites:
            out.write('\t'.join(str(x) for x in s) + '\n')
    print(f"RefEditingsites.bed created with {len(all_sites)} sites.")


def generate_gtf_intersect():
    if os.path.exists(GTF_INTERSECT):
        print(f"{GTF_INTERSECT} exists, skipping intersect.")
        return
    check_file_exists(REF_EDITING_SITES)
    check_file_exists(GTF_FILE)
    os.makedirs(FIG3A_DIR, exist_ok=True)
    print("Running bedtools intersect...")
    cmd = ["bedtools", "intersect",
           "-a", REF_EDITING_SITES, "-b", GTF_FILE, "-wa", "-wb"]
    with open(GTF_INTERSECT, 'w') as out:
        subprocess.run(cmd, stdout=out, check=True)
    print(f"Intersect result saved to {GTF_INTERSECT}")


def parse_gtf_and_annotate():
    if os.path.exists(GENE_ANNO):
        print(f"{GENE_ANNO} exists, skipping gene annotation parsing.")
        return
    check_file_exists(GTF_INTERSECT)
    os.makedirs(FIG3A_DIR, exist_ok=True)
    print("Parsing GTF intersect file...")
    parsed = os.path.join(FIG3A_DIR, "parsed_attrs.txt")
    cmd = f"""
    awk -F'\\t' '{{
        site = $1 "\\t" $2 "\\t" $3 "\\t" $4
        feature = $9
        attr = $15
        gene_name = "."; gene_type = "."; transcript_id = "."
        split(attr, a, ";")
        for (i in a) {{
            gsub(/^[ \\t]+|[ \\t]+$/, "", a[i])
            if (a[i] ~ /^gene_name/) {{ split(a[i], b, " "); gene_name = b[2]; gsub(/"/, "", gene_name) }}
            if (a[i] ~ /^gene_type/) {{ split(a[i], b, " "); gene_type = b[2]; gsub(/"/, "", gene_type) }}
            if (a[i] ~ /^transcript_id/) {{ split(a[i], b, " "); transcript_id = b[2]; gsub(/"/, "", transcript_id) }}
        }}
        print site, feature, gene_name, gene_type, transcript_id
    }}' OFS='\\t' {GTF_INTERSECT} > {parsed}
    """
    subprocess.run(cmd, shell=True, check=True)

    sorted_parsed = os.path.join(FIG3A_DIR, "sorted_parsed.txt")
    subprocess.run(f"sort -k1,1 -k2,2n -k4,4 {parsed} > {sorted_parsed}",
                   shell=True, check=True)

    site_agg = os.path.join(FIG3A_DIR, "site_agg.txt")
    subprocess.run(
        f"bedtools groupby -i {sorted_parsed} -g 1,2,3,4 -c 5,6,7,8 "
        f"-o distinct,distinct,distinct,distinct > {site_agg}",
        shell=True, check=True)

    print("Determining region types...")
    df = pd.read_csv(site_agg, sep='\t', header=None,
                     names=['chr', 'start', 'end', 'name', 'feature_list',
                            'gene_name_list', 'gene_type_list', 'transcript_list'])
    exonic_features = {'exon', 'CDS', 'UTR', 'start_codon', 'stop_codon',
                       'five_prime_UTR', 'three_prime_UTR'}

    def get_region(feature_str):
        features = set(feature_str.split(','))
        if features & exonic_features:
            return 'exonic'
        elif 'transcript' in features or 'gene' in features:
            return 'intronic'
        return 'intergenic'

    df['region'] = df['feature_list'].apply(get_region)
    df.to_csv(GENE_ANNO, sep='\t', index=False,
              columns=['chr', 'start', 'end', 'name', 'region',
                       'gene_name_list', 'gene_type_list', 'transcript_list'])
    print(f"Gene annotation saved to {GENE_ANNO}")


def load_annovar_with_chunks():
    check_file_exists(ANNO_OUT)
    print("Loading ANNOVAR file in chunks...")
    usecols = ['Chr', 'Start', 'End', 'Func.refGene']
    chunk_list = []
    for i, chunk in enumerate(pd.read_csv(ANNO_OUT, sep='\t', usecols=usecols,
                                          chunksize=CHUNKSIZE, low_memory=True)):
        print(f"Processing chunk {i+1}...")
        chunk.columns = chunk.columns.str.strip().str.lower()
        chunk['start'] = chunk['start'].apply(safe_int_convert)
        chunk['end']   = chunk['end'].apply(safe_int_convert)
        chunk_list.append(chunk[['chr', 'start', 'end', 'func.refgene']])
        gc.collect()
    df = pd.concat(chunk_list, ignore_index=True)
    df = df.drop_duplicates(subset=['chr', 'start'], keep='first')
    print(f"ANNOVAR loaded: {len(df)} unique sites")
    gc.collect()
    return df


def load_gene_type_with_chunks():
    check_file_exists(GENE_ANNO)
    print("Loading gene annotation file in chunks...")
    usecols = ['chr', 'start', 'end', 'name', 'gene_type_list']
    chunk_list = []

    def select_highest_priority(types_str):
        if pd.isna(types_str) or types_str == '.':
            return 'intergenic'
        types = [t.strip().lower() for t in str(types_str).split(',')]
        if any('pseudogene' in t for t in types):
            return 'pseudogene'
        best, best_priority = None, 100
        for t in types:
            if t == 'protein_coding':
                prio, label = 1, 'protein_coding'
            elif t == 'lncrna':
                prio, label = 2, 'lncRNA'
            else:
                prio, label = 3, 'others'
            if prio < best_priority:
                best_priority, best = prio, label
        return best if best is not None else 'others'

    for i, chunk in enumerate(pd.read_csv(GENE_ANNO, sep='\t', usecols=usecols,
                                          chunksize=CHUNKSIZE, low_memory=True)):
        print(f"Processing gene chunk {i+1}...")
        chunk.columns = chunk.columns.str.strip().str.lower()
        chunk['gene_type'] = chunk['gene_type_list'].apply(select_highest_priority)
        chunk['start'] = chunk['start'].apply(safe_int_convert)
        chunk['end']   = chunk['end'].apply(safe_int_convert)
        chunk_list.append(chunk[['chr', 'start', 'end', 'name', 'gene_type']])
        gc.collect()
    df = pd.concat(chunk_list, ignore_index=True)
    df = df.drop_duplicates(subset=['chr', 'start'], keep='first')
    print(f"Gene annotation loaded: {len(df)} unique sites")
    gc.collect()
    return df


def merge_and_prioritize_region(annovar_series):
    priority = {'exonic': 1, 'splicing': 1, 'ncRNA': 2, 'UTR': 3,
                'intronic': 4, 'up/downstream': 5, 'intergenic': 6}

    def process_single(val):
        if pd.isna(val) or val == 'intergenic':
            return 'intergenic'
        parts = [p.strip() for p in str(val).split(';')]
        merged = set()
        for p in parts:
            if p in ['UTR3', 'UTR5']:
                merged.add('UTR')
            elif p in ['upstream', 'downstream']:
                merged.add('up/downstream')
            elif p.startswith('ncRNA_'):
                merged.add('ncRNA')
            else:
                merged.add(p)
        return min(merged, key=lambda x: priority.get(x, 6))

    return annovar_series.apply(process_single)


def classify_gene_type(gene_type_series):
    return gene_type_series.astype(str)


def plot_combined_stacked_percent_bars(region_counts, type_counts, out_file):
    region_counts = region_counts.copy()
    if 'intergenic' in region_counts.index:
        region_counts = region_counts.drop('intergenic')
    if region_counts.empty:
        print("Warning: No region categories left after removing intergenic.")
        return

    for cat in ['protein_coding', 'lncRNA', 'others', 'intergenic']:
        if cat not in type_counts.index:
            type_counts[cat] = 0
    type_counts = type_counts[['protein_coding', 'lncRNA', 'others', 'intergenic']]

    region_percent = region_counts / region_counts.sum() * 100
    type_percent   = type_counts   / type_counts.sum()   * 100

    all_subcats = set(region_counts.index).union(set(type_counts.index))
    contrib = {s: region_percent.get(s, 0) + type_percent.get(s, 0) for s in all_subcats}
    sorted_subcats = sorted(all_subcats, key=lambda x: contrib[x], reverse=True)

    categories = ['Gene Region', 'Gene Type']
    data = np.array([[region_percent.get(s, 0), type_percent.get(s, 0)]
                     for s in sorted_subcats])

    colors = plt.cm.Set3(np.linspace(0, 1, len(sorted_subcats)))
    if len(sorted_subcats) >= 10:
        colors[9] = np.array([0.85, 0.33, 0.1, 1.0])

    fig, ax = plt.subplots(figsize=(8, 6))
    bottom = np.zeros(2)
    handles, labels = [], []
    for i, sub in enumerate(sorted_subcats):
        bar = ax.bar(categories, data[i], bottom=bottom, color=colors[i], label=sub)
        bottom += data[i]
        handles.append(bar)
        labels.append(sub)

    ax.set_ylabel('Percentage (%)')
    ax.set_ylim(0, 100)
    ax.set_title('Composition of Gene Regions and Gene Types')
    ax.legend(handles, labels, title="Categories",
              bbox_to_anchor=(1.05, 1), loc='upper left')
    plt.tight_layout()
    plt.savefig(out_file, dpi=150, bbox_inches='tight')
    plt.close(fig)
    print(f"Saved combined stacked bar chart to {out_file}")


